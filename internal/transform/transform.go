func inverseDCT4(coeffs []int32) []int32 {
	out := make([]int32, 16)
	tmp := make([]int32, 16)

	// 1D inverse DCT on columns (vertical pass first, matching HM/libde265)
	for c := range 4 {
		for i := range 4 {
			var sum int32
			for j := range 4 {
				sum += DCT4[j][i] * coeffs[c+j*4]
			}
			tmp[c+i*4] = clip16((sum + 64) >> 7)
		}
	}

	// 1D inverse DCT on rows (horizontal pass second)
	for y := range 4 {
		for i := range 4 {
			var sum int32
			for j := range 4 {
				sum += DCT4[j][i] * tmp[y*4+j]
			}
			out[y*4+i] = clip16((sum + 2048) >> 12)
		}
	}
	return out
}

// clip16 clips to [-32768, 32767] per HEVC spec 8.6.4.1
func clip16(v int32) int32 {
	if v < -32768 {
		return -32768
	}
	if v > 32767 {
		return 32767
	}
	return v
}

